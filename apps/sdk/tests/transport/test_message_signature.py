"""🇺🇸 RFC 9421 request signatures with the token: the normative vectors, and a base written by hand.

Two independent checks. The vectors (`vectors/service-account-token-v1.json`,
generated by the TypeScript reference) pin `Signature-Input`, `Signature`
and `Content-Digest` byte for byte, with ML-DSA in its deterministic
variant. Then a base written *by hand*, line by line, is verified against
the SDK's `Signature` with oracles that do not share the SDK's base builder:
PyNaCl for the Ed25519 half (its key derived with `cryptography`'s HKDF),
the enclave's verifier for the ML-DSA-65 half — the base construction
against the service account token spec (§4).

🇧🇷 Assinaturas de requisição RFC 9421 com o token: os vetores normativos, e uma base escrita à mão.

Duas conferências independentes. Os vetores
(`vectors/service-account-token-v1.json`, gerados pela referência em
TypeScript) fixam `Signature-Input`, `Signature` e `Content-Digest` byte a
byte, com o ML-DSA na variante determinística. Depois uma base escrita *à
mão*, linha a linha, é verificada contra o `Signature` do SDK com oráculos
que não dividem o montador de base do SDK: PyNaCl para a metade Ed25519 (a
chave derivada com o HKDF do `cryptography`), o verificador do enclave para a
metade ML-DSA-65 — a montagem da base contra a spec do token (§4).
"""

from __future__ import annotations

import base64
import hashlib
import json
import re
import secrets
from typing import Any

import httpx
import pytest
from _tokens import mint
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from nacl.exceptions import BadSignatureError
from nacl.signing import SigningKey

from diagnos.crypto.token_keys import TokenKeys, decode_token, verify_signature
from diagnos.transport.message_signature import content_digest, identity_headers, signature_base, wire_target
from diagnos.transport.service_token import DiagnosToken

from conftest import VECTORS

TOKEN_VECTORS: dict[str, Any] = json.loads((VECTORS / "service-account-token-v1.json").read_text(encoding="utf-8"))


def _keys(text: str) -> TokenKeys:
    """🇺🇸 The enclave keys of a vector token. 🇧🇷 As chaves do enclave de um token de vetor."""
    decoded = decode_token(text)
    assert not isinstance(decoded, str), decoded
    return TokenKeys.from_seed(decoded[1])


@pytest.mark.parametrize(
    ("vector", "request_"),
    [(vector, request) for vector in TOKEN_VECTORS["vectors"] for request in vector["requests"]],
    ids=lambda case: case["name"],
)
def test_every_vector_request_gets_the_reference_headers_byte_for_byte(
    vector: dict[str, Any], request_: dict[str, Any]
) -> None:
    """🇺🇸 Same `created` and nonce, deterministic ML-DSA: the three headers equal the reference's exactly.

    🇧🇷 Mesmo `created` e nonce, ML-DSA determinístico: os três headers iguais aos da referência.
    """
    keys = _keys(vector["token"])
    params = re.search(r";created=(\d+);.*;nonce=\"([A-Za-z0-9_-]{22})\";", request_["headers"]["Signature-Input"])
    assert params is not None
    body = (request_["body_utf8"] or "").encode("utf-8")
    url = httpx.URL(request_["url"])
    headers = identity_headers(
        lambda message: keys.sign(message, deterministic=True),
        keyid=vector["key_id"],
        method=request_["method"],
        url=url,
        body=body,
        created=int(params[1]),
        nonce=params[2],
    )
    assert headers == request_["headers"]
    path, _, query = url.raw_path.decode("ascii").partition("?")
    base = signature_base(
        method=request_["method"],
        path=path,
        query=query,
        digest=headers.get("Content-Digest"),
        params=headers["Signature-Input"].removeprefix("diagnos="),
    )
    assert base == request_["signature_base"]


def _ed25519_seed(seed: bytes) -> bytes:
    """🇺🇸 Spec §3, by `cryptography`: HKDF-SHA-256(seed, "diagnos-sa-token-v1", "ed25519"). 🇧🇷 Spec §3, independente."""
    return HKDF(algorithm=hashes.SHA256(), length=32, salt=b"diagnos-sa-token-v1", info=b"ed25519").derive(seed)


def _token() -> tuple[DiagnosToken, bytes]:
    """🇺🇸 A token minted now, plus its seed for the oracle. 🇧🇷 Um token criado agora, mais a semente para o oráculo."""
    seed = secrets.token_bytes(32)
    return DiagnosToken.parse(mint("wsVector", seed=seed), source="test"), seed


def _signature_bytes(header: str) -> bytes:
    """🇺🇸 `diagnos=:<base64>:` → raw bytes. 🇧🇷 `diagnos=:<base64>:` → bytes crus."""
    match = re.fullmatch(r"diagnos=:([A-Za-z0-9+/]+={0,2}):", header)
    assert match is not None, header
    return base64.b64decode(match[1])


def _verify_both(token: DiagnosToken, seed: bytes, base: str, header: str) -> None:
    """🇺🇸 3373 bytes; Ed25519 by PyNaCl, ML-DSA-65 by the enclave. 🇧🇷 3373 bytes; as duas metades conferidas."""
    signature = _signature_bytes(header)
    assert len(signature) == 64 + 3309
    SigningKey(_ed25519_seed(seed)).verify_key.verify(base.encode(), signature[:64])
    keys = token.public_keys
    assert verify_signature(
        base64.urlsafe_b64decode(keys["ed25519"] + "="),
        base64.urlsafe_b64decode(keys["ml_dsa_65"] + "=" * (-len(keys["ml_dsa_65"]) % 4)),
        base.encode(),
        signature,
    )


def test_a_post_with_query_and_body_signs_the_base_the_vault_rebuilds() -> None:
    """🇺🇸 The hand-written base for `POST …?b=2&a=1` with a JSON body verifies under both of the token's keys.

    🇧🇷 A base escrita à mão para `POST …?b=2&a=1` com corpo JSON verifica sob as duas chaves do token.
    """
    token, seed = _token()
    body = b'{"name":"Ana","note":"caf\xc3\xa9"}'
    url = httpx.URL("https://vault.example/api/external/v1/workspaces/wsVector/patients?b=2&a=%2F1")
    headers = token.request_headers("post", url, body, 1_760_000_000)

    nonce = re.search(r';nonce="([A-Za-z0-9_-]{22})";', headers["Signature-Input"])
    assert nonce is not None
    digest = "sha-256=:" + base64.b64encode(hashlib.sha256(body).digest()).decode() + ":"
    params = (
        '("@method" "@path" "@query" "content-digest");created=1760000000;'
        f'keyid="{token.key_id}";nonce="{nonce[1]}";alg="ed25519+ml-dsa-65"'
    )
    expected_base = (
        '"@method": POST\n'
        '"@path": /api/external/v1/workspaces/wsVector/patients\n'
        '"@query": ?b=2&a=%2F1\n'
        f'"content-digest": {digest}\n'
        f'"@signature-params": {params}'
    )
    assert headers["Signature-Input"] == f"diagnos={params}"
    assert headers["Content-Digest"] == digest
    assert "Authorization" not in headers
    _verify_both(token, seed, expected_base, headers["Signature"])


def test_a_get_without_query_covers_only_method_and_path() -> None:
    """🇺🇸 No query, no body: no `@query`, no `content-digest`, no `Content-Digest` header; `keyid` is `svc_<hex>`.

    🇧🇷 Sem query, sem corpo: sem `@query`, sem `content-digest`, sem header `Content-Digest`; `keyid` é `svc_<hex>`.
    """
    token, seed = _token()
    url = httpx.URL("https://vault.example/api/external/v1/workspaces/wsVector/session")
    headers = token.request_headers("GET", url, b"", 1_760_000_001)
    assert headers["Signature-Input"].startswith(
        f'diagnos=("@method" "@path");created=1760000001;keyid="{token.key_id}";'
    )
    assert headers["Signature-Input"].endswith(';alg="ed25519+ml-dsa-65"')
    assert "Content-Digest" not in headers
    params = headers["Signature-Input"].removeprefix("diagnos=")
    base = f'"@method": GET\n"@path": /api/external/v1/workspaces/wsVector/session\n"@signature-params": {params}'
    _verify_both(token, seed, base, headers["Signature"])


def test_either_half_alone_does_not_verify() -> None:
    """🇺🇸 Breaking the Ed25519 or the ML-DSA half, or dropping one, fails — the vault requires both.

    🇧🇷 Quebrar a metade Ed25519 ou a ML-DSA, ou tirar uma, falha — o cofre exige as duas.
    """
    token, seed = _token()
    signature = token.sign(b"base")
    keys = token.public_keys
    ed = base64.urlsafe_b64decode(keys["ed25519"] + "=")
    ml = base64.urlsafe_b64decode(keys["ml_dsa_65"] + "=" * (-len(keys["ml_dsa_65"]) % 4))
    assert verify_signature(ed, ml, b"base", signature)
    for index in (0, 64 + 100):
        broken = bytearray(signature)
        broken[index] ^= 1
        assert not verify_signature(ed, ml, b"base", bytes(broken))
    assert not verify_signature(ed, ml, b"base", signature[:64])
    with pytest.raises(BadSignatureError):
        SigningKey(_ed25519_seed(seed)).verify_key.verify(b"other", signature[:64])


def test_every_attempt_gets_a_fresh_nonce_and_signature() -> None:
    """🇺🇸 Two calls with identical inputs never share a nonce — a retry is never a replay.

    🇧🇷 Duas chamadas com entradas idênticas nunca dividem um nonce — retentar nunca é replay.
    """
    token, _ = _token()
    url = httpx.URL("https://vault.example/x")
    first = token.request_headers("POST", url, b"{}", 1)
    second = token.request_headers("POST", url, b"{}", 1)
    assert first["Signature-Input"] != second["Signature-Input"]
    assert first["Signature"] != second["Signature"]


def test_building_blocks_match_rfc9530_and_rfc9421_framing() -> None:
    """🇺🇸 `Content-Digest` of an empty body; a base with a query, no body. 🇧🇷 Digest vazio; base com query."""
    assert content_digest(b"") == "sha-256=:47DEQpj8HBSa+/TImW+5JCeuQeRkm5NMpJWZG3hSuFU=:"
    base = signature_base(method="get", path="/p", query="x=1", digest=None, params="()")
    assert base == '"@method": GET\n"@path": /p\n"@query": ?x=1\n"@signature-params": ()'
    headers = identity_headers(
        lambda message: b"\x00" * 64, keyid="k", method="GET", url=httpx.URL("/p"), body=b"", created=5, nonce="n"
    )
    assert headers == {
        "Signature-Input": 'diagnos=("@method" "@path");created=5;keyid="k";nonce="n";alg="ed25519+ml-dsa-65"',
        "Signature": "diagnos=:" + base64.b64encode(b"\x00" * 64).decode() + ":",
    }


# 🇺🇸 What `new URL()` (the vault's parser) prints as `pathname + search` for these targets, recorded from Node.
# 🇧🇷 O que o `new URL()` (o parser do cofre) imprime como `pathname + search` para estes alvos, gravado do Node.
WHATWG_VECTORS = [
    ("/api/x/a'b?q=it's", "/api/x/a'b?q=it%27s"),
    ('/api/x/caf%C3%A9/{id}?q="a"&r=<b>&s=a`b&t=%27', "/api/x/caf%C3%A9/%7Bid%7D?q=%22a%22&r=%3Cb%3E&s=a`b&t=%27"),
    ("/api/x/a|b^c[d]?q=x|y^z[w]&u=é", "/api/x/a|b^c[d]?q=x|y^z[w]&u=%C3%A9"),
    ("/api/x/a b?q=a b", "/api/x/a%20b?q=a%20b"),
]


def test_wire_target_matches_what_the_vaults_url_parser_rebuilds() -> None:
    """🇺🇸 After httpx and `wire_target`, the target equals Node's `new URL()` output, byte for byte.

    🇧🇷 Depois do httpx e do `wire_target`, o alvo é igual à saída do `new URL()` do Node, byte a byte.
    """
    client = httpx.Client(base_url="https://vault.example")
    for written, whatwg in WHATWG_VECTORS[:3]:
        raw = client.build_request("GET", written).url.raw_path.decode("ascii")
        assert wire_target(raw) == whatwg, written
        assert wire_target(whatwg) == whatwg
    assert wire_target(WHATWG_VECTORS[3][0]) == WHATWG_VECTORS[3][1]


def test_the_transport_sends_and_signs_the_normalized_target() -> None:
    """🇺🇸 A query `'` goes out as `%27`, and is signed so. 🇧🇷 Um `'` sai como `%27`, assinado."""
    from diagnos.transport.config import Settings
    from diagnos.transport.http import VaultTransport

    token, seed = _token()
    seen: list[httpx.Request] = []

    def handler(request: httpx.Request) -> httpx.Response:
        if request.url.path == "/time":
            return httpx.Response(200, json={"result": 1_760_000_000_000})
        seen.append(request)
        return httpx.Response(200, json={"success": True, "result": None})

    transport = VaultTransport(
        Settings(token=token, vault_url="https://vault.example"),
        token,
        session_keys=lambda: None,
        client=httpx.Client(base_url="https://vault.example", transport=httpx.MockTransport(handler)),
    )
    transport.get("/api/external/v1/x?cursor=it's", signed=False)
    request = seen[0]
    assert request.url.raw_path == b"/api/external/v1/x?cursor=it%27s"
    params = request.headers["Signature-Input"].removeprefix("diagnos=")
    base = f'"@method": GET\n"@path": /api/external/v1/x\n"@query": ?cursor=it%27s\n"@signature-params": {params}'
    _verify_both(token, seed, base, request.headers["Signature"])
